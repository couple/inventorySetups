//
// type: "item" - a single swappable item, shown as one dropdown.
//   { type: "item", key, label, variants, default? }
//   key:      short, unique, stable id - used as the localStorage key, so
//             once people start choosing preferences, avoid changing it.
//   label:    display name for the preference's row on the Preferences page.
//   variants: options the user can choose between. Each entry is either a
//             plain item id, or `{ id, name?, icon? }` to override the
//             text and/or icon shown next to it on the Preferences page
//             (handy when the item's wiki-derived name is ugly, e.g.
//             `{ id: 30351, name: "Dragon pickaxe (or)(tbrl)" }`, or its
//             wiki image doesn't match, e.g.
//             `{ id: 12345, icon: "Some_other_item.png" }` - a filename
//             resolved against the wiki's image path, or a full URL).
//             Both only affect the Preferences page itself, not the icon
//             shown once the item's actually substituted into a real
//             setup elsewhere on the site.
//             Unless overridden by `default` below, the FIRST entry is the
