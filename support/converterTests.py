def find_node() -> str | None:
    """Return the Node.js executable available on PATH."""
    return shutil.which("node") or shutil.which("nodejs")


def json_loads_if_possible(value: Any) -> Any:
    """
    Parse converter output as JSON when possible.

    Inventory Setup output is JSON. Bank Tag Layout output isn't.
    """
    if not isinstance(value, str):
        return value

    try:
        return json.loads(value)
    except (json.JSONDecodeError, TypeError):
        return value

# Item ids allowed to keep an "f": true flag when normalizing JSON output
# before comparison. All other ids have "f": true stripped.
KEEP_F_FLAG_IDS = {27281, 27510, 27509, 27282}
def normalize_f_flags(data: Any) -> Any:
    """
    Recursively strip "f": true from any item object whose "id" is not in
    KEEP_F_FLAG_IDS. Applied to both expected and actual JSON before
    comparison so "f" differences on other ids don't fail tests.
    """
    if isinstance(data, dict):
        normalized = {key: normalize_f_flags(value) for key, value in data.items()}

        if (
            "id" in normalized
            and "f" in normalized
            and normalized["id"] not in KEEP_F_FLAG_IDS
        ):
            del normalized["f"]

        return normalized

    if isinstance(data, list):
        return [normalize_f_flags(item) for item in data]

    return data

def get_path(data: Any, path: str) -> Any:
    """
    Get a nested value using paths such as:

        setup.name
        setup.sb
        setup.rp.0.id
        layout.4
    """
    current = data

    for part in path.split("."):
        if isinstance(current, list):
            try:
                index = int(part)
            except ValueError:
                raise KeyError(path)

            if index >= len(current):
                raise KeyError(path)

            current = current[index]

        elif isinstance(current, dict):
            if part not in current:
                raise KeyError(path)

            current = current[part]

        else:
            raise KeyError(path)

    return current


def format_value(value: Any) -> str:
    """Compact single-line representation for failure messages."""
    if isinstance(value, str):
        return value

    return json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    )


def assert_expected(test: dict[str, Any], actual: str) -> None:
    """
    Assert the output according to the test definition.

    Supported expectation formats:

        "expected": "exact string"

        "expected": {...}
            Structural JSON equality.

        "expected_contains": {
            "setup.name": "test",
            "layout.4": 123,
        }

        "expected_contains": {
            "contains": ["123:4", "456:5"]
        }
    """

    # ------------------------------------------------------------------
    # Exact expected output
    # ------------------------------------------------------------------

    if "expected" in test:
        expected = test["expected"]

        expected_parsed = json_loads_if_possible(expected)
        actual_parsed = json_loads_if_possible(actual)

        if isinstance(expected_parsed, str) or isinstance(actual_parsed, str):
            # Not JSON on at least one side (e.g. Bank Tag Layout output) -
            # fall back to an exact string comparison.
            if actual != expected:
                raise AssertionError(
                    "Output does not match expected string.\n\n"
                    f"Expected:\n{expected}\n\n"
                    f"Actual:\n{actual}"
                )

        else:
            expected_normalized = normalize_f_flags(expected_parsed)
            actual_normalized = normalize_f_flags(actual_parsed)

            if actual_normalized != expected_normalized:
                raise AssertionError(
                    "Output JSON does not match expected value.\n\n"
                    f"Expected:\n{format_value(expected_normalized)}\n\n"
                    f"Actual:\n{format_value(actual_normalized)}"
                )

    # ------------------------------------------------------------------
    # Partial expected output
    # ------------------------------------------------------------------

    contains = test.get("expected_contains")

    if not contains:
        return

    # String contains checks.
    if "contains" in contains:
        for fragment in contains["contains"]:
            if fragment not in actual:
                raise AssertionError(
                    "Expected output to contain:\n"
                    f"  {fragment}\n\n"
                    f"Actual:\n{actual}"
                )

    # Nested JSON value checks.
    json_expectations = {
        key: value
        for key, value in contains.items()
        if key != "contains"
    }

    if not json_expectations:
        return

    actual_json = json_loads_if_possible(actual)

    if isinstance(actual_json, str):
        raise AssertionError(
            "Expected JSON output, but converter returned a string:\n"
            f"{actual}"
        )

    for path, expected_value in json_expectations.items():
        try:
            actual_value = get_path(actual_json, path)
        except KeyError:
            raise AssertionError(
                f"Expected JSON path {path!r} to exist.\n\n"
                f"Actual:\n{format_value(actual_json)}"
            )

        if actual_value != expected_value:
            raise AssertionError(
                f"Value at {path!r} does not match.\n\n"
                f"Expected:\n{format_value(expected_value)}\n\n"
                f"Actual:\n{format_value(actual_value)}"
            )


def run_test(
    node: str,
    runner: Path,
    test: dict[str, Any],
) -> str:
    """Run one test case through the real JavaScript converter."""

    environment = {
        "CONVERTER_FILE": str(CONVERTER_FILE),
        "ITEMS_DATA_FILE": (
            str(ITEMS_DATA_FILE)
            if ITEMS_DATA_FILE.exists()
            else ""
        ),
    }

    process = subprocess.run(
        [node, str(runner)],
        input=json.dumps(test),
        text=True,
        capture_output=True,
        env={
            **dict(__import__("os").environ),
            **environment,
        },
    )

    if process.returncode != 0:
        raise RuntimeError(
            "Node.js test runner failed.\n\n"
            f"stdout:\n{process.stdout}\n\n"
            f"stderr:\n{process.stderr}"
        )

    try:
        response = json.loads(process.stdout)
    except json.JSONDecodeError:
        raise RuntimeError(
            "Node.js returned invalid test-runner output.\n\n"
            f"stdout:\n{process.stdout}\n\n"
            f"stderr:\n{process.stderr}"
        )

    if not response.get("ok"):
        raise AssertionError(
            "Converter threw an error:\n"
            f"{response.get('error', 'Unknown error')}"
        )

    return response["output"]


